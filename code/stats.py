"""Descriptive statistics of the included papers.
Reads supplement/S5_extraction_table.tsv and writes data/summary_statistics.md.
Run from the repository root:  python3 code/stats.py"""
import collections, csv, os, re

D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(D, 'supplement', 'S5_extraction_table.tsv'), encoding='utf-8', newline='') as f:
    inc = list(csv.DictReader(f, delimiter='\t'))
FINEST, TUMOUR = 'Finest evaluation unit', 'Tumour type'
rev = [r for r in inc if r[FINEST] == 'Review (no own results)' or r['Paper type'] == 'Review']
non = [r for r in inc if r not in rev]
ft = [r for r in non if r['Evidence basis'] == 'Full text']
ab = [r for r in non if r['Evidence basis'] != 'Full text']
UNITS = ['Lesion', 'Patient', 'Image', 'Voxel', 'Unknown']

def count(rows, col):
    return collections.Counter(r[col] or 'Not recorded' for r in rows)

def fmt(c):
    return ', '.join('%s %d' % (k, v) for k, v in c.most_common())

def lead(rows, col):
    """First word of a Yes/No/Unknown/Not applicable style field."""
    return collections.Counter((re.split(r'[:;(,]', r[col])[0].strip() or 'Not recorded') for r in rows)

o = []
w = o.append
w('# Summary statistics of the included papers\n')
w('Generated by `code/stats.py` from `supplement/S5_extraction_table.tsv`.\n')
w('Included **%d** papers (%d reviews, %d primary studies); of the primary studies, full text was read for %d and only the abstract for %d.\n'
  % (len(inc), len(rev), len(non), len(ft), len(ab)))
w('| Dimension | Distribution (%d included papers) |\n|---|---|' % len(inc))
w('| Search line | %s |' % fmt(count(inc, 'Search line')))
w('| Tumour type | %s |' % fmt(count(inc, TUMOUR)))
w('| Paper type | %s |' % fmt(count(inc, 'Paper type')))
yr = collections.Counter(r['Year'] for r in inc)
w('| Year | %s |\n' % '; '.join('%s %d' % (k, yr[k]) for k in sorted(yr)))
w('## Finest evaluation unit (primary studies)\n')
w('| Scope | Papers | ' + ' | '.join(UNITS) + ' |\n|---|---|' + '---|' * len(UNITS))
for name, L in [('All primary studies', non), ('Full text read', ft), ('Abstract only', ab)]:
    c = count(L, FINEST)
    w('| %s | %d | %s |' % (name, len(L), ' | '.join('%d (%.0f%%)' % (c[u], 100 * c[u] / len(L)) if u == 'Lesion' else str(c[u]) for u in UNITS)))
w('')
w('### By tumour type (primary studies, full text read)\n')
w('| Tumour type | Papers | ' + ' | '.join(UNITS) + ' |\n|---|---|' + '---|' * len(UNITS))
for t in ['Glioma', 'Brain metastasis', 'Meningioma', 'Paediatric', 'Multiple types', 'Unknown']:
    L = [r for r in ft if r[TUMOUR] == t]
    c = count(L, FINEST)
    w('| %s | %d | %s |' % (t, len(L), ' | '.join(str(c[u]) for u in UNITS)))
w('')
w('## Lesion-level detail (primary studies)\n')
for name, L in [('Full text read', ft), ('Abstract only', ab)]:
    w('**%s (%d papers)**' % (name, len(L)))
    for col in ['Lesion-level metrics', 'Lesion-level rules', 'Stratified by lesion size', 'External validation', 'Handling of missed lesions']:
        w('- %s: %s' % (col, fmt(lead(L, col))))
    w('')
w('## Risk estimation\n')
rk = [r for r in inc if r['Risk evaluation unit'] != '']
w('%d of the %d included papers describe a risk-estimation method (%d of them reviews).\n' % (len(rk), len(inc), sum(r in rev for r in rk)))
pr = [r for r in rk if r not in rev]
w('Evaluation unit of the risk estimate (primary studies, n = %d): %s' % (len(pr), fmt(count(pr, 'Risk evaluation unit'))))
open(os.path.join(D, 'data', 'summary_statistics.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
